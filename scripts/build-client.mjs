// @ts-check
/**
 * Builds the browser bundle for the settings page.
 *
 * DSH loads client plugins as prebuilt bundles, so this script wraps the esbuild
 * output in the `window.__ModuleLoader__.load({ id, factory })` envelope the
 * loader expects. Run `node scripts/build-client.mjs --check` in CI to make sure
 * `lib/client.js` is committed in sync with `src/client.jsx`.
 */
import { build } from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const target = path.join(root, 'lib', 'client.js')
const checkOnly = process.argv.includes('--check')

const result = await build({
  entryPoints: [path.join(root, 'src', 'client.jsx')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['es2022'],
  jsx: 'automatic',
  external: ['react', 'react/jsx-runtime'],
  charset: 'utf8',
  legalComments: 'none',
  logLevel: 'warning',
})

const code = result.outputFiles?.[0]?.text ?? ''
const indented = code
  .split('\n')
  .map((line) => (line.length > 0 ? `\t\t${line}` : line))
  .join('\n')

const banner = `// dsh-restart-guard client bundle — generated by scripts/build-client.mjs; do not edit.\n`
const bundle = `${banner}window.__ModuleLoader__.load({\n\tid: "dsh-restart-guard",\n\tfactory: (require) => {\n\t\tvar module = { exports: {} };\n\t\tvar exports = module.exports;\n${indented}\n\t\treturn module.exports;\n\t}\n});\n`

if (checkOnly) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (current !== bundle) {
    console.error('lib/client.js is out of date: run `node scripts/build-client.mjs`')
    process.exit(1)
  }
  console.log('client bundle is up to date')
  process.exit(0)
}

fs.writeFileSync(target, bundle)
console.log(`wrote ${path.relative(root, target)} (${bundle.length} bytes)`)
